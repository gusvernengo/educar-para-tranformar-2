-- A. Inspeccionar si existen registros legacy con columnas incompletas
SELECT id, created_at, nombre, dni, nivel, email, estado
FROM public.inscripciones
WHERE nombre IS NULL OR dni IS NULL OR nivel IS NULL OR email IS NULL;

-- B. Estructura y nulabilidad de public.inscripciones
SELECT column_name, data_type, is_nullable
FROM information_schema.columns
WHERE table_schema = 'public'
AND table_name = 'inscripciones'
ORDER BY ordinal_position;

-- C. Listado de perfiles y roles registrados
SELECT id, email, role
FROM public.profiles;

-- D. Verificación de políticas RLS activas en inscripciones y profiles
SELECT policyname, cmd, roles
FROM pg_policies
WHERE schemaname = 'public'
AND tablename IN ('inscripciones', 'profiles')
ORDER BY tablename, policyname;
