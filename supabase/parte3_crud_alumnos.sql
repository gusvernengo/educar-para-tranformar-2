-- 1. Crear tabla public.alumnos
CREATE TABLE IF NOT EXISTS public.alumnos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    legajo TEXT UNIQUE NOT NULL,
    nombre TEXT NOT NULL,
    dni TEXT NOT NULL UNIQUE,
    nivel TEXT NOT NULL,
    curso TEXT NOT NULL,
    idioma TEXT,
    deporte TEXT,
    tutor TEXT NOT NULL,
    regularidad TEXT NOT NULL DEFAULT 'Regular',
    asistencia TEXT NOT NULL DEFAULT '100%',
    CONSTRAINT alumnos_regularidad_check CHECK (regularidad IN ('Regular', 'Condicional'))
);

-- 2. Habilitar Row Level Security (RLS)
ALTER TABLE public.alumnos ENABLE ROW LEVEL SECURITY;

-- 3. Políticas RLS exclusivas para Administradores Autenticados
-- Utiliza la función existente public.is_admin()

DROP POLICY IF EXISTS "alumnos_select_admin" ON public.alumnos;
CREATE POLICY "alumnos_select_admin" ON public.alumnos
    FOR SELECT
    TO authenticated
    USING (public.is_admin());

DROP POLICY IF EXISTS "alumnos_insert_admin" ON public.alumnos;
CREATE POLICY "alumnos_insert_admin" ON public.alumnos
    FOR INSERT
    TO authenticated
    WITH CHECK (public.is_admin());

DROP POLICY IF EXISTS "alumnos_update_admin" ON public.alumnos;
CREATE POLICY "alumnos_update_admin" ON public.alumnos
    FOR UPDATE
    TO authenticated
    USING (public.is_admin())
    WITH CHECK (public.is_admin());

DROP POLICY IF EXISTS "alumnos_delete_admin" ON public.alumnos;
CREATE POLICY "alumnos_delete_admin" ON public.alumnos
    FOR DELETE
    TO authenticated
    USING (public.is_admin());

-- 4. Permisos (GRANT) para el rol authenticated
GRANT SELECT, INSERT, UPDATE, DELETE ON public.alumnos TO authenticated;

-- 5. Consulta de verificación
SELECT column_name, data_type, is_nullable, column_default
FROM information_schema.columns
WHERE table_schema = 'public' AND table_name = 'alumnos'
ORDER BY ordinal_position;
